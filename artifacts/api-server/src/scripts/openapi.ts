/** Write docs/api/openapi.yaml from the live route registry. */
import fs from "node:fs";
import path from "node:path";
import { stringify } from "yaml";
import { loadConfig } from "../config/env";
import { createContext } from "../context";
import { createApp } from "../app";
import { buildOpenApi } from "../modules/openapi";

const config = loadConfig({ ...process.env, NODE_ENV: "production", DATABASE_URL: process.env.DATABASE_URL ?? "postgres://x@localhost/x", APP_SECRET: "openapi-generation-only-not-a-real-secret-value", EMAIL_DRIVER: "smtp", SMTP_HOST: "localhost" });
const app = createContext(config);
createApp(app);
const doc = buildOpenApi();
const out = path.resolve(import.meta.dirname, "../../../../docs/api/openapi.yaml");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `# Generated by \`pnpm --filter @workspace/api-server run openapi\` — do not edit by hand.\n${stringify(doc, { lineWidth: 0 })}`);
console.log(`wrote ${out} (${Object.keys(doc.paths).length} paths)`);
await app.dbHandle.close();
